function makeLocalIso(daysOffset: number, hour: number, minute: number = 0): string {
  const now = new Date();
  const d = new Date(now.getFullYear(), now.getMonth(), now.getDate() + daysOffset, hour, minute, 0, 0);
  return d.toISOString();
}

